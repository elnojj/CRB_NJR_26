export const BLUEPRINT_SCREEN_BY_ID: Record<BlueprintScreenId, BlueprintScreenSpec> =
  Object.fromEntries(BLUEPRINT_SCREENS.map((s) => [s.id, s])) as Record<
    BlueprintScreenId,
    BlueprintScreenSpec
  >;

export function listBlueprintScreensByStatus(status: BlueprintScreenStatus): BlueprintScreenSpec[] {
  return BLUEPRINT_SCREENS.filter((s) => s.status === status);
}

export function blueprintStatusSummary(): Record<BlueprintScreenStatus, number> {
  return BLUEPRINT_SCREENS.reduce(
    (acc, s) => {
      acc[s.status] += 1;
      return acc;
    },
    {
      IMPLEMENTED: 0,
      PARTIAL: 0,
      MISSING: 0,
      BLOCKED: 0,
      VERIFIED: 0,
    } as Record<BlueprintScreenStatus, number>
  );
}

export function panelIdForBlueprintScreen(id: BlueprintScreenId): string | null {
  return BLUEPRINT_SCREEN_BY_ID[id]?.panelId ?? null;
}
