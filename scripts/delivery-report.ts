import { writeFileSync } from 'node:fs';
import { JOURNEY_BEATS } from '../src/three/camera/journeyConfig.ts';
import { getMediaRecord } from '../src/data/journeyMediaManifest.ts';
import { environmentOfAssociation, getNode } from '../src/data/environmentRegistry.ts';

const fmt = (s: number) => `${Math.floor(s / 60)}:${String(Math.floor(s % 60)).padStart(2, '0')}`;
const rows = JOURNEY_BEATS.map((b, i) => {
  const node = b.nodeId ? getNode(b.nodeId) : null;
  const env = b.nodeId ? environmentOfAssociation(b.nodeId)?.id ?? '-' : 'master';
  const assets = b.assetIds.map((id) => getMediaRecord(id));
  const assetIds = b.assetIds.join('<br>') || '-';
  const src = assets.map((a) => (a ? a.sourceUrl : '?')).join('<br>') || '-';
  const runtime = assets.map((a) => a?.runtimeUrl ?? 'UNRESOLVED').join('<br>') || '-';
  const tc = assets.some((a) => a && a.timecodes.length) ? 'see manifest' : 'none selected';
  const status =
    b.evidence === 'gap'
      ? assets.length ? 'GAP (stand-in footage, no dedicated artefact)' : 'GAP'
      : b.evidence === 'assets'
        ? assets.every((a) => a?.runtimeUrl) ? 'mapped + local file (unplayed)' : 'mapped, runtime UNRESOLVED'
        : b.evidence.toUpperCase();
  return `| ${i + 1} | ${b.jId} (${fmt(b.startSec)}-${fmt(b.endSec)}) | ${env} | ${node?.associationId ?? b.nodeId ?? '-'} | ${assetIds} | ${src} | ${runtime} | ${tc} | ${status} |`;
});
const md = `# Cerebro delivery report (generated)

Generated by \`scripts/delivery-report.ts\` from \`journeyConfig.ts\`, \`environmentRegistry.ts\` and \`journeyMediaManifest.ts\`.
Nothing here has been verified on the live app. "UNRESOLVED" means no authorized same-origin runtime route exists for that Drive file.

| # | Beat (time) | Environment | Node | Asset id | Source URL | Runtime asset path | Timecode | Status |
|---|---|---|---|---|---|---|---|---|
${rows.join('\n')}

## Verification status

Run: tsc, \`scripts/run-self-tests.ts\` (node:test), both Vite builds, headless Chrome (swiftshader, fake camera) smoke on the local dev server.

Not verified: live Vercel app, iPad Safari (portrait and landscape), real two-hand tracking, Drive video playback (CORS, range/seek, loop, mute), NASA agent card UI (data only), world-space subtitles (DOM overlay), automatic media-tile open per beat.
`;
writeFileSync('docs/CEREBRO_DELIVERY_REPORT.md', md);
console.log(rows.length, 'rows');
